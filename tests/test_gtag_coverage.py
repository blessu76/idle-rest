"""GA4 coverage: every public index.html loads gtag with the one measurement ID — run: python3 -m unittest discover -s tests

Exceptions are explicit (a new page without gtag fails here until it is added on purpose):
  - redirect stubs (meta refresh + noindex, no analytics by design): redirect stubs written by build_journal.py / build_pages.py (non-en/ko privacy·terms → en)
  - ALLOWLIST: pages that are intentionally bare
content/ holds build sources (fragments), scripts/ and tests/ are not public — all skipped.
"""
import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GA_ID = "G-XG4BH800J0"
SKIP_TOP = ("content", "scripts", "tests", "assets", "node_modules", ".git")
ALLOWLIST = {
    "404.html",  # hand-written, noindex, no scripts at all
}


def public_html():
    for p in sorted(REPO.rglob("*.html")):
        rel = p.relative_to(REPO)
        if rel.parts[0] in SKIP_TOP:
            continue
        yield rel.as_posix(), p.read_text(encoding="utf-8")


def is_redirect_stub(text):
    head = text.split("</head>")[0]
    return ("generated by scripts/build_journal.py" in head or "generated by scripts/build_pages.py" in head) and "redirect stub" in head \
        and 'http-equiv="refresh"' in head and "noindex" in head


class GtagCoverage(unittest.TestCase):
    def test_every_public_page_has_gtag_or_is_an_allowed_exception(self):
        missing = []
        for rel, text in public_html():
            if rel in ALLOWLIST or is_redirect_stub(text):
                continue
            if "googletagmanager.com/gtag/js" not in text or "gtag('config'" not in text.replace('gtag("config"', "gtag('config'"):
                missing.append(rel)
        self.assertEqual(missing, [], "public pages without the GA4 snippet (fix the generator/template, not the HTML; or add to ALLOWLIST on purpose)")

    def test_all_gtag_pages_use_the_one_measurement_id(self):
        other = []
        for rel, text in public_html():
            if "googletagmanager.com/gtag/js" not in text:
                continue
            ids = set(re.findall(r"G-[A-Z0-9]{8,}", text))
            if ids != {GA_ID}:
                other.append((rel, sorted(ids)))
        self.assertEqual(other, [])

    def test_allowlist_entries_exist_and_stay_bare(self):
        for rel in ALLOWLIST:
            p = REPO / rel
            self.assertTrue(p.exists(), "stale ALLOWLIST entry: %s" % rel)
            self.assertNotIn("googletagmanager", p.read_text(encoding="utf-8"), "%s now has gtag — drop it from ALLOWLIST" % rel)


if __name__ == "__main__":
    unittest.main()
