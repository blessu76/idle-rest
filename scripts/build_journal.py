def parse_post(path):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        raise ValueError("missing front matter (file must start with ---)")
    end = text.find("\n---", 4)
    if end == -1:
        raise ValueError("front matter is not closed with ---")
    meta = {}
    for line in text[4:end].split("\n"):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise ValueError("bad front matter line: %r" % line)
        k, v = line.split(":", 1)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        meta[k.strip().lower()] = v
    body = text[end + 4:].lstrip("\n")
    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        raise ValueError("missing front matter: " + ", ".join(missing))
    if not SLUG_RE.match(meta["slug"]):
        raise ValueError("slug must match [a-z0-9-]+: %r" % meta["slug"])
    if meta["slug"] in LANGS or meta["slug"] in ("feed", "page"):
        raise ValueError("slug %r is reserved (language codes, 'feed' and 'page' are URL segments)" % meta["slug"])
    if meta["lang"] not in LANGS:
        raise ValueError("lang must be one of %s: %r" % (" ".join(LANGS), meta["lang"]))
    if meta.get("translation"):
        raise ValueError("`translation:` was removed — all language versions of a post share the same slug; use `translation_of: <ko|en>` on the translated version")
    of = meta.get("translation_of")
    if meta["lang"] not in MAIN_LANGS and not of:
        raise ValueError("lang %s is an AI translation: `translation_of: en` (or ko) is required" % meta["lang"])
    if of and (of not in MAIN_LANGS or of == meta["lang"]):
        raise ValueError("translation_of must be the language code of the ko/en original (ko or en, not this post's own language): %r" % of)
    try:
        meta["_date"] = dt.date.fromisoformat(meta["date"])
    except ValueError:
        raise ValueError("date must be YYYY-MM-DD: %r" % meta["date"])
    if meta.get("time"):
        if not re.match(r"^(?:[01]\d|2[0-3]):[0-5]\d$", meta["time"]):
            raise ValueError("time must be HH:MM (24h, KST): %r" % meta["time"])
        meta["_pub"] = "%sT%s:00+09:00" % (meta["date"], meta["time"])
    else:
        meta["_pub"] = "%sT%s:00+09:00" % (meta["date"], PUB_FALLBACK_HM)  # always ISO +09:00 (date-only shown on screen)
    meta["draft"] = str(meta.get("draft", "false")).lower() in ("true", "yes", "1")
    if not meta["draft"] and not meta.get("time") and meta["_date"] >= TIME_REQUIRED_FROM:
        raise ValueError("time: HH:MM (KST) is required for posts dated %s or later (use the real first-commit/publish time)" % TIME_REQUIRED_FROM)
    if meta.get("updated"):
        try:
            dt.date.fromisoformat(meta["updated"])
        except ValueError:
            raise ValueError("updated must be YYYY-MM-DD: %r" % meta["updated"])
    # dateModified: a date-only `updated` on the publish day must not precede the timed datePublished
    meta["_mod"] = meta["_pub"] if meta.get("updated") in (None, "", meta["date"]) else meta["updated"]
    meta["_aliases"] = []
    for a in [x.strip() for x in meta.get("aliases", "").split(",") if x.strip()]:
        if not re.match(r"^/(?:journal|[a-z]{2}/journal)/[a-z0-9/-]*$", a):
            raise ValueError("alias must be a site path like /journal/old-slug/ : %r" % a)
        meta["_aliases"].append(a if a.endswith("/") else a + "/")
    meta["_keywords"] = [x.strip() for x in meta.get("keywords", "").split(",") if x.strip()]
    meta["_album"] = (parse_entries(meta["album"]) or [None])[0] if meta.get("album") else None
    meta["_songs"] = parse_entries(meta.get("songs", ""))
    meta["_citations"] = parse_entries(meta.get("citations", ""))
    meta["_body"] = body
    meta["_src"] = path.name
    return meta


def parse_entries(v):
    """'Title @ url | Title @ url' -> [(title, url|None)]. url must be http(s) or site-relative."""
    out = []
    for part in v.split("|"):
        part = part.strip()
        if not part:
            continue
        title, _, url = part.rpartition(" @ ") if " @ " in part else (part, "", "")
        title, url = title.strip(), url.strip()
        if url and not re.match(r"^(https?://|/)", url):
            raise ValueError("bad url in %r (need http(s):// or /path)" % part)
        out.append((title, abs_url(url) if url else None))
    return out


