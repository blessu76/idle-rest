def inline(text):
    parts = re.split(r"(`[^`]+`)", text)
    out = []
    for p in parts:
        if len(p) > 1 and p.startswith("`") and p.endswith("`"):
            out.append("<code>%s</code>" % esc(p[1:-1]))
            continue
        s = esc(p)
        s = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)",
                   lambda m: img_tag(safe_url(html.unescape(m.group(2))), html.unescape(m.group(1))), s)

        def link(m):
            url = safe_url(html.unescape(m.group(2)))
            ext = url.startswith("http") and not url.startswith(SITE)
            return '<a href="%s"%s>%s</a>' % (esc(url), ' rel="noopener"' if ext else "", m.group(1))
        s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<!\*)\*(?![\s*])(.+?)(?<![\s*])\*(?!\*)", r"<em>\1</em>", s)
        s = re.sub(r"(?<![\w_])_(?!\s)(.+?)(?<!\s)_(?![\w_])", r"<em>\1</em>", s)
        out.append(s)
    return "".join(out)


def markdown(src):
    lines = src.split("\n")
    out, para, i = [], [], 0

    def flush():
        if para:
            out.append("<p>%s</p>" % inline(" ".join(x.strip() for x in para)))
            para.clear()

    while i < len(lines):
        line = lines[i]
        st = line.strip()
        if st.startswith("```"):
            flush()
            code = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            out.append("<pre><code>%s</code></pre>" % esc("\n".join(code)))
            i += 1
            continue
        if not st:
            flush()
            i += 1
            continue
        fm = FIG_RE.match(st)
        if fm:  # a line that is only an image -> <figure>; optional "caption" after the url
            flush()
            cap = "<figcaption>%s</figcaption>" % inline(fm.group(3)) if fm.group(3) else ""
            out.append("<figure>%s%s</figure>" % (img_tag(safe_url(fm.group(2)), fm.group(1)), cap))
            i += 1
            continue
        m = re.match(r"^(#{1,4})\s+(.*)$", st)
        if m:
            flush()
            level = {1: 2, 2: 2, 3: 3, 4: 4}[len(m.group(1))]
            out.append("<h%d>%s</h%d>" % (level, inline(m.group(2)), level))
            i += 1
            continue
        if re.match(r"^(-{3,}|\*{3,})$", st):
            flush()
            out.append("<hr>")
            i += 1
            continue
        if st.startswith("|") and i + 1 < len(lines) and TABLE_SEP_RE.match(lines[i + 1].strip()):
            flush()  # GFM table: header row, |---|---| row, body rows; wrapped so 320px scrolls sideways instead of overflowing
            cells = lambda row: [c.strip() for c in row.strip().strip("|").split("|")]
            head_cells = cells(st)
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(cells(lines[i]))
                i += 1
            n = len(head_cells)
            th = "".join('<th scope="col">%s</th>' % inline(c) for c in head_cells)
            tr = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c) for c in (r + [""] * n)[:n]) for r in rows)
            out.append('<div class="table-wrap" tabindex="0"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (th, tr))
            continue
        if st.startswith(">"):
            flush()
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(lines[i].strip()[1:].strip())
                i += 1
            out.append("<blockquote><p>%s</p></blockquote>" % inline(" ".join(quote)))
            continue
        if re.match(r"^[-*+]\s+", st) or re.match(r"^\d+[.)]\s+", st):
            flush()
            ordered = bool(re.match(r"^\d", st))
            pat = r"^\d+[.)]\s+" if ordered else r"^[-*+]\s+"
            items = []
            while i < len(lines) and re.match(pat, lines[i].strip()):
                items.append(re.sub(pat, "", lines[i].strip()))
                i += 1
            tag = "ol" if ordered else "ul"
            out.append("<%s>%s</%s>" % (tag, "".join("<li>%s</li>" % inline(x) for x in items), tag))
            continue
        para.append(line)
        i += 1
    flush()
    return "\n".join(out)


