def render_sitemap_block(posts):
    if not posts:
        return ""
    rows = ["  <url>\n    <loc>%s/journal/</loc>\n    <lastmod>%s</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>0.6</priority>\n  </url>"
            % (SITE, posts[0]["_date"].isoformat())]
    for p in posts:
        rows.append("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n    <priority>0.5</priority>\n  </url>"
                    % (post_url(p), (p.get("updated") or p["_date"].isoformat())))
    return "\n".join(rows) + "\n"


def replace_between(text, start_re, end_marker, new, where):
    m = re.search(start_re, text)
    e = text.find(end_marker)
    if not m or e == -1 or e < m.end():
        raise SystemExit("marker not found in %s: %s ... %s" % (where, start_re, end_marker))
    return text[:m.end()] + "\n" + new + ("\n" if new and not new.endswith("\n") else "") + text[e:]


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent), help="site root (default: this repo)")
    ap.add_argument("--drafts", action="store_true", help="include draft posts (preview only — never commit the result)")
    ap.add_argument("--check", action="store_true", help="validate posts only, write nothing")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    src = root / "content" / "journal"
    global ADS_ATTR
    m = re.search(r'<html[^>]*\sdata-ads="(on|off)"', (root / "index.html").read_text(encoding="utf-8"))
    ADS_ATTR = m.group(1) if m else "off"

    posts, errors, slugs = [], [], {}
    for f in sorted(src.glob("*.md")) if src.is_dir() else []:
        if f.name.lower() == "readme.md":
            continue
        try:
            p = parse_post(f)
        except ValueError as ex:
            errors.append("%s: %s" % (f.name, ex))
            continue
        if p["slug"] in slugs:
            errors.append("%s: slug %r already used by %s" % (f.name, p["slug"], slugs[p["slug"]]))
            continue
        slugs[p["slug"]] = f.name
        if p["draft"] and not a.drafts:
            continue
        p["_html"] = markdown(p["_body"])
        posts.append(p)
    if errors:
        print("journal: errors\n  " + "\n  ".join(errors), file=sys.stderr)
        return 1
    posts.sort(key=lambda p: (p["_date"], p["slug"]), reverse=True)
    if a.check:
        print("journal: OK — %d post(s) ready%s" % (len(posts), " (incl. drafts)" if a.drafts else ""))
        return 0

    out = root / "journal"
    out.mkdir(exist_ok=True)
    live = {p["slug"] for p in posts}
    # remove pages this script generated earlier for posts that are gone / now draft
    for d in out.iterdir():
        if d.is_dir() and d.name not in live:
            idx = d / "index.html"
            if idx.exists() and GEN_MARK in idx.read_text(encoding="utf-8"):
                shutil.rmtree(d)
    for p in posts:
        (out / p["slug"]).mkdir(exist_ok=True)
        (out / p["slug"] / "index.html").write_text(render_post(p), encoding="utf-8")
    (out / "index.html").write_text(render_list(posts), encoding="utf-8")
    (out / "feed.xml").write_text(render_feed(posts), encoding="utf-8")

    sm = root / "sitemap.xml"
    sm.write_text(replace_between(sm.read_text(encoding="utf-8"), r"<!-- journal:start[^>]*-->",
                                  "  <!-- journal:end -->", render_sitemap_block(posts), "sitemap.xml"), encoding="utf-8")
    home = root / "index.html"
    home_html = replace_between(home.read_text(encoding="utf-8"), r"<!-- journal:home:start[^>]*-->",
                           "<!-- journal:home:end -->", render_home_cards(posts), "index.html")
    # no posts -> hide the whole home Journal section (menu link stays); >=1 post -> show it. Idempotent.
    home_html, n = re.subn(r'(<section class="section" id="journal"[^>]*?)( hidden)?>',
                      lambda m: m.group(1) + ("" if posts else " hidden") + ">", home_html, count=1)
    if n != 1:
        raise SystemExit('home <section id="journal"> not found in index.html')
    home.write_text(home_html, encoding="utf-8")
    print("journal: built %d post(s)%s → %s" % (len(posts), " (incl. drafts)" if a.drafts else "", out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
