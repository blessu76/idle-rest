def hero_image(p):
    """front matter image -> first body asset image -> None (caller falls back to og-image)."""
    if p.get("image"):
        return p["image"]
    m = re.search(r"!\[[^\]]*\]\((/assets/journal/[^)\s]+)", p["_body"])
    return m.group(1) if m else None


def body_images(p):
    seen, out = set(), []
    for u in ([p["image"]] if p.get("image") else []) + re.findall(r"!\[[^\]]*\]\((/assets/[^)\s]+)", p["_body"]):
        if u not in seen:
            seen.add(u)
            out.append(u)
    return out


def check_post_images(p):
    """Errors for local images (front matter `image` + body `![](/assets/...)`) that are not real files."""
    errs = []
    for u in body_images(p):
        if not u.startswith("/"):
            continue  # external URL — not ours to check
        f = (ROOT / urllib.parse.unquote(re.split(r"[?#]", u, 1)[0]).lstrip("/")).resolve()
        if ROOT not in f.parents or not f.is_file():
            errs.append("%s: image file not found: %s" % (p["_src"], u))
    return errs


def check_translations(posts, all_posts, drafts_ok):
    """Errors for hreflang/translation pairs: target exists, not self, not a hidden draft, and mutual."""
    errs = []
    for p in posts:
        src, me = p["_src"], p["slug"]
        tr, of = p.get("translation"), p.get("translation_of")
        if of and not tr:
            errs.append("%s: translation_of %r needs `translation: %s` too (pairs are written on both posts)" % (src, of, of))
        if of and tr and of != tr:
            errs.append("%s: translation_of %r and translation %r must name the same post" % (src, of, tr))
        for k, v in (("translation", tr), ("translation_of", of)):
            if not v:
                continue
            if v == me:
                errs.append("%s: %s points at the post itself (%r)" % (src, k, v))
                continue
            other = all_posts.get(v)
            if other is None:
                errs.append("%s: %s refers to unknown slug %r" % (src, k, v))
            elif other["draft"] and not drafts_ok:
                errs.append("%s: %s refers to draft post %r (draft pages are not published)" % (src, k, v))
            elif k == "translation" and other.get("translation") != me:
                errs.append("%s: translation %r does not point back (add `translation: %s` to %s)" % (src, v, me, other["_src"]))
    return errs


def image_obj(rel, caption=None):
    url = abs_url(rel)
    wh = image_size(rel)
    if not wh and not caption:
        return url
    o = {"@type": "ImageObject", "url": url}
    if wh:
        o["width"], o["height"] = wh
    if caption:
        o["caption"] = caption
    return o


def plain_text(html_body):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", html_body))).strip()


def thing(kind, title, url):
    o = {"@type": kind, "name": title, "byArtist": {"@type": "MusicGroup", "name": "ipe()", "url": "https://ipe.rest/"}}
    if url:
        o["url" if url.startswith(SITE) else "sameAs"] = url
    return o


def citations(p):
    out, seen = [], set()
    for t, u in p["_citations"]:
        if u not in seen:
            seen.add(u)
            out.append({"@type": "CreativeWork", "name": t or u, "url": u})
    for m in re.finditer(r'<a href="(https?://[^"]+)" rel="noopener">(.*?)</a>', p["_html"]):
        u = html.unescape(m.group(1))
        host = re.sub(r"^www\.", "", u.split("/")[2].lower())
        if u in seen or any(host == h or host.endswith("." + h) for h in SOCIAL_HOSTS):
            continue
        seen.add(u)
        out.append({"@type": "CreativeWork", "name": plain_text(m.group(2)) or u, "url": u})
    return out


def breadcrumb(lang, name, url):
    t = ui(lang)
    items = [(t["home"], SITE + "/"), (t["journal"], SITE + "/journal/")] + ([(name, url)] if name else [])
    return {"@context": "https://schema.org", "@type": "BreadcrumbList",
            "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n, "item": u} for i, (n, u) in enumerate(items)]}


def alternates(p, by_slug):
    """hreflang <link>s: self + translation + x-default (English version if there is one, else self)."""
    other = by_slug.get(p.get("translation") or "")
    pair = {p["lang"]: post_url(p)}
    if other:
        pair.setdefault(other["lang"], post_url(other))
    default = pair.get("en", post_url(p))
    rows = ['<link rel="alternate" hreflang="%s" href="%s">' % (esc(l), esc(u)) for l, u in sorted(pair.items())]
    rows.append('<link rel="alternate" hreflang="x-default" href="%s">' % esc(default))
    return "\n".join(rows) + "\n"


def render_post(p, by_slug=None):
    by_slug = by_slug or {}
    t = ui(p["lang"])
